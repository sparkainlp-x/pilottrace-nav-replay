"""Replay orchestration: simulate -> map to 512-value frames -> score through pilottrace -> evidence.

Every frame is scored twice: by the unmodified, hash-pinned ``pilottrace`` package (the scoring of
record) and by this repository's fail-closed reference adapter. The two must agree on every latch
decision, otherwise the run is refused.
"""

from __future__ import annotations

import json
import math
from collections.abc import Iterable, Sequence
from dataclasses import replace
from pathlib import Path
from typing import Any

from ._deps import load_pilottrace
from .integrations.oes_adapter import (
    BLOCK_WIDTH,
    CHANNELS,
    FailClosedError,
    frames_from_residuals,
    score_frame,
)
from .provenance.evidence_report import build_evidence, render_markdown
from .provenance.manifest import build_manifest, pretty_json, verify_manifest
from .scenarios import INERTIAL_PROFILES, SCENARIOS, EpochRecord, ScenarioSpec, SimConfig, simulate

#: Agreement tolerance between pilottrace's scale-normalised arithmetic and the adapter's direct formula.
SCORE_TOLERANCE = 1e-12
DROPOUT_COMPARISON_SCENARIO = "total_dropout"


def _r(value: float | None, digits: int = 6) -> float | None:
    return None if value is None else round(value, digits) + 0.0


def pilottrace_manifest(config: SimConfig, spec: ScenarioSpec) -> dict[str, Any]:
    """Declarations required by pilottrace (schema 1); they describe this replay's mapping exactly."""
    return {
        "schema_version": 1,
        "threshold": config.tau,
        "channel_order": (
            "Block b (values 32b..32b+31) is residual channel b of pilottrace_nav.integrations.oes_adapter.CHANNELS "
            "over the 32 most recent 1 Hz epochs, oldest first."
        ),
        "units": "dimensionless: each channel divided by its declared scale (|value| = 1 is one declared tolerance)",
        "scaling": "Per-channel declared scales from oes_adapter.CHANNELS; values rounded to 9 decimals.",
        "timebase": "One frame per 1 Hz SYNTHETIC epoch; the frame for epoch t covers epochs t-31..t.",
        "baseline_preprocessing": "Zero reference (x_ref = 0); no filtering or baseline correction.",
        "missing_value_policy": (
            "A missing measurement sets its residual to 0.0 and its availability channel to 1.0; NaN or "
            "infinite values fail closed before scoring."
        ),
        "source_provenance": (
            f"SYNTHETIC scenario '{spec.name}' generated by pilottrace-nav-replay, seed {config.seed}, "
            f"inertial profile '{config.inertial_profile}'."
        ),
        "permitted_use": "Offline software replay and demonstration only; not navigation, safety or operational use.",
    }


def _trace_bytes(frames: Sequence[tuple[int, list[float]]], labels: Sequence[bool]) -> bytes:
    doc = {"frames": [{"values": frame, "label": label} for (_, frame), label in zip(frames, labels, strict=True)]}
    return json.dumps(doc, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _frame_labels(records: Sequence[EpochRecord], frames: Sequence[tuple[int, list[float]]]) -> list[bool]:
    """A frame is labelled degraded when any epoch in its 32-epoch window is degraded."""
    return [any(r.degraded for r in records[t - BLOCK_WIDTH + 1 : t + 1]) for t, _ in frames]


def _cross_check(frames: Sequence[tuple[int, list[float]]], report: dict[str, Any], tau: float) -> dict[str, Any]:
    if report["input_summary"]["frames_rejected"]:
        raise FailClosedError(f"pilottrace rejected {report['input_summary']['frames_rejected']} frame(s)")
    max_diff = 0.0
    disagreements = 0
    max_r = [0.0] * len(CHANNELS)
    for (_, frame), result in zip(frames, report["frames"], strict=True):
        ours = score_frame(frame, tau)
        theirs = [block["score"] for block in result["blocks"]]
        max_diff = max(max_diff, max(abs(a - b) for a, b in zip(ours.scores, theirs, strict=True)))
        if list(ours.latched_blocks) != result["flagged_block_indices"]:
            disagreements += 1
        max_r = [max(a, b) for a, b in zip(max_r, ours.residual_max, strict=True)]
    if disagreements or max_diff > SCORE_TOLERANCE:
        raise FailClosedError(
            f"adapter and pilottrace disagree (latch disagreements={disagreements}, max |dS|={max_diff:.3g})"
        )
    return {
        "frames_compared": len(frames),
        "latch_disagreements": disagreements,
        "max_abs_score_difference": max_diff,
        "max_residual_R_by_channel": {c.name: _r(v) for c, v in zip(CHANNELS, max_r, strict=True)},
    }


def _event_metrics(
    spec: ScenarioSpec, records: Sequence[EpochRecord], frame_results: Sequence[dict[str, Any]], dt: float
) -> list[dict[str, Any]]:
    by_epoch = {fr["epoch"]: fr for fr in frame_results}
    out = []
    for event in spec.events:
        # Scoring window: event epochs plus the 31 epochs whose frames still contain event epochs.
        window = range(event.start, min(event.end + BLOCK_WIDTH - 1, len(records)))
        latched = [t for t in window if t in by_epoch and by_epoch[t]["flagged"]]
        during_event = [t for t in latched if t < event.end]
        channels: dict[str, int] = {}
        for t in latched:
            for b in by_epoch[t]["flagged_block_indices"]:
                channels[CHANNELS[b].name] = channels.get(CHANNELS[b].name, 0) + 1
        during = [r.nav_error_m for r in records[event.start : event.end]]
        if not during:  # the event lies entirely after the end of a shortened run
            out.append({"kind": event.kind, "start_epoch": event.start, "end_epoch_exclusive": event.end,
                        "params": dict(event.params), "within_run": False})
            continue
        last = records[min(event.end, len(records)) - 1]
        out.append(
            {
                "kind": event.kind,
                "start_epoch": event.start,
                "end_epoch_exclusive": event.end,
                "params": dict(event.params),
                "within_run": True,
                "detected_during_event": bool(during_event),
                "detection_latency_s": (during_event[0] - event.start) * dt if during_event else None,
                "latched_frames_during_event": len(during_event),
                "latched_frames_after_end": len(latched) - len(during_event),
                "first_latch_epoch": latched[0] if latched else None,
                "latched_channels": dict(sorted(channels.items())),
                "expected_channel_latched_during_event": any(
                    CHANNELS[b].name in spec.expected_channels
                    for t in during_event
                    for b in by_epoch[t]["flagged_block_indices"]
                ),
                "nav_error_max_during_m": _r(max(during)),
                "nav_error_at_event_end_m": _r(last.nav_error_m),
            }
        )
    return out


def run_scenario(spec: ScenarioSpec, config: SimConfig | None = None) -> dict[str, Any]:
    """Run one scenario end to end. Returns the summary plus the exact pilottrace input/output bytes."""
    config = config or SimConfig()
    pilottrace, pin_hashes = load_pilottrace()
    records = simulate(spec, config)
    frames = frames_from_residuals([r.residuals for r in records])
    labels = _frame_labels(records, frames)
    trace = _trace_bytes(frames, labels)
    manifest = pretty_json(pilottrace_manifest(config, spec))
    report = pilottrace.analyze_bytes(trace, manifest)
    check = _cross_check(frames, report, config.tau)

    frame_results = [
        {"epoch": t, "flagged": fr["flagged"], "flagged_block_indices": fr["flagged_block_indices"], "label": label}
        for (t, _), fr, label in zip(frames, report["frames"], labels, strict=True)
    ]
    false_alarms = [fr["epoch"] for fr in frame_results if fr["flagged"] and not fr["label"]]
    latched_channels: dict[str, int] = {}
    for fr in frame_results:
        for b in fr["flagged_block_indices"]:
            latched_channels[CHANNELS[b].name] = latched_channels.get(CHANNELS[b].name, 0) + 1
    nominal_errors = [r.nav_error_m for r in records if not r.degraded]
    classification = report["labeled_frame_classification"]
    summary = {
        "name": spec.name,
        "title": spec.title,
        "description": spec.description,
        "evidence_tag": "SYNTHETIC",
        "epochs": len(records),
        "frames": len(frames),
        "frames_labelled_degraded": sum(labels),
        "frames_latched": report["input_summary"]["flagged_frames"],
        "false_alarm_frames": len(false_alarms),
        "false_alarm_first_epochs": false_alarms[:10],
        "latched_frames_by_channel": dict(sorted(latched_channels.items())),
        "pilottrace_confusion_counts": classification.get("confusion_counts"),
        "pilottrace_descriptive_metrics": {
            key: _r(classification.get(key))
            for key in (
                "descriptive_precision",
                "descriptive_recall_sensitivity",
                "descriptive_specificity",
                "descriptive_f1_score",
            )
        },
        "events": _event_metrics(spec, records, frame_results, config.dt),
        "nav_error_m": {
            "max": _r(max(r.nav_error_m for r in records)),
            "max_outside_events": _r(max(nominal_errors)) if nominal_errors else None,
            "mean_outside_events": _r(math.fsum(nominal_errors) / len(nominal_errors)) if nominal_errors else None,
            "final": _r(records[-1].nav_error_m),
        },
        "cross_check": check,
        "pilottrace_hashes": report["hashes"],
    }
    return {
        "summary": summary,
        "trace_bytes": trace,
        "manifest_bytes": manifest,
        "report_bytes": pilottrace.report_json(report).encode("utf-8"),
        "pin_hashes": pin_hashes,
    }


def dropout_profile_comparison(config: SimConfig) -> list[dict[str, Any]]:
    """Dead-reckoning error during the total-dropout scenario under each assumed inertial profile."""
    spec = SCENARIOS[DROPOUT_COMPARISON_SCENARIO]
    event = spec.events[0]
    if event.end > config.epochs:
        return []  # the dropout does not fit in a shortened run
    rows = []
    for name, profile in INERTIAL_PROFILES.items():
        records = simulate(spec, replace(config, inertial_profile=name))
        during = [r.nav_error_m for r in records[event.start : event.end]]
        rows.append(
            {
                "inertial_profile": name,
                "gyro_bias_dps": profile.gyro_bias_dps,
                "gyro_noise_dps": profile.gyro_noise_dps,
                "dropout_s": (event.end - event.start) * config.dt,
                "nav_error_at_dropout_end_m": _r(records[event.end - 1].nav_error_m),
                "nav_error_max_during_dropout_m": _r(max(during)),
                "note": profile.note,
            }
        )
    return rows


def scenario_catalogue(names: Iterable[str]) -> dict[str, Any]:
    return {
        name: {
            "title": SCENARIOS[name].title,
            "description": SCENARIOS[name].description,
            "events": [
                {"kind": e.kind, "start": e.start, "end": e.end, "params": dict(e.params)}
                for e in SCENARIOS[name].events
            ],
            "expected_channels": list(SCENARIOS[name].expected_channels),
        }
        for name in names
    }


def run_replay(
    out_dir: str | Path, scenarios: Sequence[str] | None = None, config: SimConfig | None = None
) -> dict[str, Any]:
    """Run the replay pack and write traces, pilottrace reports, the evidence report and the manifest."""
    config = config or SimConfig()
    names = list(scenarios) if scenarios else list(SCENARIOS)
    unknown = [n for n in names if n not in SCENARIOS]
    if unknown or len(set(names)) != len(names):
        raise ValueError(f"unknown or duplicate scenario(s): {', '.join(unknown) or 'duplicates'}")
    out = Path(out_dir)
    outputs: dict[str, bytes] = {}
    summaries = []
    pin_hashes: dict[str, str] = {}
    for name in names:
        result = run_scenario(SCENARIOS[name], config)
        summaries.append(result["summary"])
        pin_hashes = result["pin_hashes"]
        outputs[f"traces/{name}_trace.json"] = result["trace_bytes"]
        outputs[f"traces/{name}_pilottrace_manifest.json"] = result["manifest_bytes"]
        outputs[f"traces/{name}_pilottrace_report.json"] = result["report_bytes"]
    evidence = build_evidence(config, summaries, dropout_profile_comparison(config))
    outputs["evidence_report.json"] = pretty_json(evidence)
    outputs["evidence_report.md"] = render_markdown(evidence).encode("utf-8")
    manifest = build_manifest(
        config=config.to_dict(),
        scenarios=scenario_catalogue(names),
        outputs=outputs,
        pilottrace_hashes=pin_hashes,
    )
    outputs["provenance_manifest.json"] = pretty_json(manifest)
    for rel, data in outputs.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_bytes(data)
        tmp.replace(path)
    problems = verify_manifest(out / "provenance_manifest.json")
    if problems:  # pragma: no cover - would indicate a filesystem fault
        raise OSError("written outputs do not match the manifest: " + "; ".join(problems))
    return evidence
